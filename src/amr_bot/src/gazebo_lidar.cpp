// 2D lidar for the Gazebo backend, no rendering involved: casts rays from the robot's true pose
// against the box collisions of the world's model.sdf and publishes /scan. Same scan layout as
// mujoco_bridge (360 beams, index 0 = behind, no return = inf). Gazebo's own gpu_lidar crashes the
// server here, see PROCESS.md. ponytail: sees only the static boxes in the file, not objects added
// to the world at runtime; subscribe to entity poses if moving obstacles are ever needed.
#include <algorithm>
#include <cmath>
#include <fstream>
#include <limits>
#include <random>
#include <regex>
#include <sstream>
#include <string>
#include <vector>

#include "nav_msgs/msg/odometry.hpp"
#include "rclcpp/rclcpp.hpp"
#include "sensor_msgs/msg/laser_scan.hpp"

class GazeboLidar : public rclcpp::Node {
public:
    GazeboLidar() : Node("gazebo_lidar") {
        const std::string sdf = declare_parameter<std::string>(
            "model_sdf", "/ros2_ws/src/amr_bot/models/gazebo/office/model.sdf");
        lidar_z_ = declare_parameter("lidar_z", 0.15);  // boxes not crossing this height are ignored
        period_ = 1.0 / declare_parameter("rate_hz", 10.0);
        noise_ = std::normal_distribution<double>(0.0, declare_parameter("noise_stddev", 0.01));

        load_boxes(sdf);
        if (boxes_.empty()) {
            RCLCPP_ERROR(get_logger(), "no boxes at z=%.2f found in %s", lidar_z_, sdf.c_str());
            rclcpp::shutdown();
            return;
        }

        scan_pub_ = create_publisher<sensor_msgs::msg::LaserScan>("/scan", 10);
        pose_sub_ = create_subscription<nav_msgs::msg::Odometry>(
            "/ground_truth/odom", 10, std::bind(&GazeboLidar::on_pose, this, std::placeholders::_1));
        RCLCPP_INFO(get_logger(), "gazebo_lidar up: %zu boxes from %s", boxes_.size(), sdf.c_str());
    }

private:
    struct Box { double x, y, c, s, hx, hy; };  // centre, cos/sin of yaw, half extents
    static constexpr int BEAMS = 360;
    static constexpr double RANGE_MIN = 0.1, RANGE_MAX = 10.0;

    // model.sdf is generated by scripts/office_to_sdf.py, so its layout is known
    void load_boxes(const std::string& path) {
        std::ifstream f(path);
        std::stringstream ss;
        ss << f.rdbuf();
        const std::string text = ss.str();
        const std::string num = "(-?[0-9.]+)";
        const std::regex re("<collision[^>]*>\\s*<pose>" + num + " " + num + " " + num + " [^ ]+ [^ ]+ " + num +
                            "</pose>\\s*<geometry><box><size>" + num + " " + num + " " + num + "</size>");
        for (auto it = std::sregex_iterator(text.begin(), text.end(), re); it != std::sregex_iterator(); ++it) {
            const auto& m = *it;
            const double z = std::stod(m[3]), yaw = std::stod(m[4]), sz = std::stod(m[7]);
            if (std::fabs(z - lidar_z_) > sz / 2) continue;
            boxes_.push_back({std::stod(m[1]), std::stod(m[2]), std::cos(yaw), std::sin(yaw),
                              std::stod(m[5]) / 2, std::stod(m[6]) / 2});
        }
    }

    // distance along the ray to the box, or +inf: slab test in the box's own frame
    static double hit(const Box& b, double ox, double oy, double dx, double dy) {
        const double px = b.c * (ox - b.x) + b.s * (oy - b.y), py = -b.s * (ox - b.x) + b.c * (oy - b.y);
        const double ux = b.c * dx + b.s * dy, uy = -b.s * dx + b.c * dy;
        double t0 = -std::numeric_limits<double>::infinity(), t1 = std::numeric_limits<double>::infinity();
        const double p[2] = {px, py}, u[2] = {ux, uy}, h[2] = {b.hx, b.hy};
        for (int i = 0; i < 2; ++i) {
            if (std::fabs(u[i]) < 1e-12) {
                if (std::fabs(p[i]) > h[i]) return std::numeric_limits<double>::infinity();
                continue;
            }
            const double a = (-h[i] - p[i]) / u[i], c = (h[i] - p[i]) / u[i];
            t0 = std::max(t0, std::min(a, c));
            t1 = std::min(t1, std::max(a, c));
        }
        if (t0 > t1 || t1 < 0) return std::numeric_limits<double>::infinity();
        return std::max(t0, 0.0);  // origin inside the box: distance 0
    }

    void on_pose(nav_msgs::msg::Odometry::ConstSharedPtr msg) {
        // Driven and stamped by Gazebo's clock, so the scan stays in step with sim time at any speed.
        const double t = rclcpp::Time(msg->header.stamp).seconds();
        if (t < last_t_) last_t_ = -1.0;  // world restarted
        if (last_t_ >= 0 && t - last_t_ < period_ - 1e-3) return;  // tolerance: 0.1 s may read as 0.0999...
        last_t_ = t;

        const auto& p = msg->pose.pose;
        const double yaw = std::atan2(2 * (p.orientation.w * p.orientation.z + p.orientation.x * p.orientation.y),
                                      1 - 2 * (p.orientation.y * p.orientation.y + p.orientation.z * p.orientation.z));
        sensor_msgs::msg::LaserScan scan;
        scan.header.stamp = msg->header.stamp;
        scan.header.frame_id = "lidar_link";
        scan.angle_min = -M_PI;
        scan.angle_increment = 2.0 * M_PI / BEAMS;
        scan.angle_max = scan.angle_min + (BEAMS - 1) * scan.angle_increment;
        scan.scan_time = period_;
        scan.range_min = RANGE_MIN;
        scan.range_max = RANGE_MAX;
        scan.ranges.resize(BEAMS);
        for (int i = 0; i < BEAMS; ++i) {
            const double a = yaw + scan.angle_min + i * scan.angle_increment;
            const double dx = std::cos(a), dy = std::sin(a);
            double best = std::numeric_limits<double>::infinity();
            for (const auto& b : boxes_) best = std::min(best, hit(b, p.position.x, p.position.y, dx, dy));
            scan.ranges[i] = best >= RANGE_MAX ? std::numeric_limits<float>::infinity()
                                               : std::max(best + noise_(rng_), RANGE_MIN);
        }
        scan_pub_->publish(scan);
    }

    double lidar_z_, period_, last_t_ = -1.0;
    std::vector<Box> boxes_;
    std::mt19937 rng_{std::random_device{}()};
    std::normal_distribution<double> noise_;
    rclcpp::Publisher<sensor_msgs::msg::LaserScan>::SharedPtr scan_pub_;
    rclcpp::Subscription<nav_msgs::msg::Odometry>::SharedPtr pose_sub_;
};

int main(int argc, char** argv) {
    rclcpp::init(argc, argv);
    auto node = std::make_shared<GazeboLidar>();
    if (rclcpp::ok()) rclcpp::spin(node);
    rclcpp::shutdown();
    return 0;
}
